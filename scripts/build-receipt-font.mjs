// Generates src/main/print/receipt-font.ts from the Terminus Font BDF sources.
//
//   node scripts/build-receipt-font.mjs <dir containing ter-u24n.bdf, ter-u24b.bdf, ter-u16n.bdf, ter-u16b.bdf>
//
// Source: terminus-font-4.49.1.tar.gz (https://terminus-font.sourceforge.net/),
// SIL OFL 1.1 — see assets/fonts/OFL-terminus.txt. Only the characters the
// server can send (Windows-1254, what `ESC t 91` tickets are written in) are
// kept, so the output is a subset: a Modified Version under the OFL, which is
// why it is not called "Terminus Font" anywhere it is used.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: node scripts/build-receipt-font.mjs <bdf dir>');
  process.exit(1);
}

/** Every character a Windows-1254 byte can stand for, printable only. */
function cp1254Chars() {
  const dec = new TextDecoder('windows-1254');
  const out = [];
  for (let b = 0x20; b <= 0xff; b++) {
    if (b === 0x7f) continue;
    const ch = dec.decode(Uint8Array.of(b));
    if (ch === '�' || ch.codePointAt(0) < 0x20 || (ch.codePointAt(0) >= 0x7f && ch.codePointAt(0) < 0xa0)) continue;
    if (!out.includes(ch)) out.push(ch);
  }
  return out;
}

function parseBdf(file) {
  const text = readFileSync(file, 'latin1');
  const header = (key) => {
    const m = text.match(new RegExp(`^${key} (.+)$`, 'm'));
    if (!m) throw new Error(`${file}: no ${key}`);
    return m[1].trim();
  };
  const [cellW, cellH, , cellYOff] = header('FONTBOUNDINGBOX').split(/\s+/).map(Number);
  const ascent = Number(header('FONT_ASCENT'));
  const glyphs = new Map();
  for (const block of text.split('STARTCHAR').slice(1)) {
    const enc = block.match(/^ENCODING (-?\d+)$/m);
    const bbx = block.match(/^BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)$/m);
    const bitmap = block.match(/^BITMAP\n([\s\S]*?)\nENDCHAR/m);
    if (!enc || !bbx || !bitmap) continue;
    const [w, h, xoff, yoff] = bbx.slice(1).map(Number);
    const rows = bitmap[1].split('\n').map((r) => r.trim()).filter(Boolean);
    glyphs.set(Number(enc[1]), { w, h, xoff, yoff, rows });
  }
  return { cellW, cellH, cellYOff, ascent, glyphs };
}

/** One glyph as `cellH` rows of `ceil(cellW/8)` bytes, MSB = leftmost dot, placed in its cell. */
function cellBytes(font, g) {
  const stride = Math.ceil(font.cellW / 8);
  const out = new Uint8Array(stride * font.cellH);
  const top = font.ascent - (g.yoff + g.h);
  for (let y = 0; y < g.h; y++) {
    const bits = BigInt('0x' + (g.rows[y] || '0'));
    const rowBits = g.rows[y].length * 4;
    for (let x = 0; x < g.w; x++) {
      if (((bits >> BigInt(rowBits - 1 - x)) & 1n) === 0n) continue;
      const cx = g.xoff + x;
      const cy = top + y;
      if (cx < 0 || cx >= font.cellW || cy < 0 || cy >= font.cellH) continue;
      out[cy * stride + (cx >> 3)] |= 0x80 >> (cx & 7);
    }
  }
  return out;
}

function build(file, chars) {
  const font = parseBdf(path.join(srcDir, file));
  const parts = [];
  let kept = '';
  for (const ch of chars) {
    const g = font.glyphs.get(ch.codePointAt(0));
    if (!g) {
      console.warn(`${file}: no glyph for U+${ch.codePointAt(0).toString(16).padStart(4, '0')} — falls back to '?'`);
      continue;
    }
    kept += ch;
    parts.push(cellBytes(font, g));
  }
  return { width: font.cellW, height: font.cellH, chars: kept, data: Buffer.concat(parts).toString('base64') };
}

const chars = cp1254Chars();
const fonts = {
  A: build('ter-u24n.bdf', chars),
  A_BOLD: build('ter-u24b.bdf', chars),
  B: build('ter-u16n.bdf', chars),
  B_BOLD: build('ter-u16b.bdf', chars),
};

const lit = (f) =>
  `{\n  width: ${f.width},\n  height: ${f.height},\n  chars: ${JSON.stringify(f.chars)},\n  data:\n    '${f.data}',\n}`;

const out = `/*
 * GENERATED by scripts/build-receipt-font.mjs — do not edit by hand.
 *
 * Bitmap glyphs for printing tickets as images ("E) Görüntü olarak").
 *
 * Derived from Terminus Font 4.49.1:
 *   Copyright (C) 2020 Dimitar Toshkov Zhekov,
 *   with Reserved Font Name "Terminus Font".
 * Licensed under the SIL Open Font License, Version 1.1 — the full text ships
 * as assets/fonts/OFL-terminus.txt (dist/main/assets/OFL-terminus.txt).
 *
 * This is a MODIFIED VERSION under the OFL (a Windows-1254 subset re-encoded
 * as packed rows), so it does not carry the Reserved Font Name.
 *
 * Layout: each glyph is \`height\` rows of ceil(width / 8) bytes, MSB = leftmost
 * dot, 1 = burn; glyph i of \`chars\` starts at byte i * rowBytes * height.
 */

export interface BitmapFont {
  width: number;
  height: number;
  chars: string;
  data: string;
}

/** Font A cell (12x24), regular and bold. */
export const FONT_A: BitmapFont = ${lit(fonts.A)};

export const FONT_A_BOLD: BitmapFont = ${lit(fonts.A_BOLD)};

/** Font B: 8x16 glyphs, drawn into the printer's 9x17 cell. */
export const FONT_B: BitmapFont = ${lit(fonts.B)};

export const FONT_B_BOLD: BitmapFont = ${lit(fonts.B_BOLD)};
`;

writeFileSync(path.join(root, 'src/main/print/receipt-font.ts'), out);
console.log(`[receipt-font] ${chars.length} chars, A=${fonts.A.chars.length} B=${fonts.B.chars.length}`);
